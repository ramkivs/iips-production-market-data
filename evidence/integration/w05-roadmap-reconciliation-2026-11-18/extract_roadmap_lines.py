#!/usr/bin/env python3
"""W05 roadmap reconciliation, 2026-11-18: verbatim extract of the roadmap lines that govern W05.

READ-ONLY. Reads one Markdown file. Writes one Markdown document to standard output.
Opens no socket. Changes nothing.

Purpose: the IRR session that implemented the W05 lifecycle line could not read this
repository. This extract carries the governing roadmap text to it through the Principal,
identified by commit, Git blob and SHA-256, so that the text can be compared without access.

Usage
  python3 extract_roadmap_lines.py <roadmap.md>

  roadmap.md  docs/integration/IIPS-CURRENT-PORTFOLIO-EXECUTION-ROADMAP.md at the commit below.

Exit codes: 0 extract written; 2 usage; 3 the file is not the recorded blob.
"""
import hashlib
import sys

ROADMAP_PATH = 'docs/integration/IIPS-CURRENT-PORTFOLIO-EXECUTION-ROADMAP.md'
MAIN_COMMIT = '2685562522f1a2fd1d745a7857f771bf21453315'
LAST_CHANGED_BY = '0e473fc16723ae21115e65dc0887caad69173c93'
GIT_BLOB = '7affba55a5ba568333fdc2961a322c2f76b4c671'
SHA256 = '875938b087bca87415c5215283967049d331d609383095ecc93adfe7e5e98e89'

# (title, [(first line, last line), ...]); line numbers are 1-based and inclusive.
SECTIONS = [
    ('1. W05 itself', [(148, 149)]),
    ('2. Work-item index: column heads, W05 and the items that depend on it', [(35, 35), (37, 38), (43, 43), (45, 45), (48, 48), (50, 50), (53, 53), (58, 58), (60, 60)]),
    ('3. Authority for every work item', [(66, 66)]),
    ('4. Decisions GD-1 to GD-3 and their framing', [(19, 19), (21, 25), (31, 31)]),
    ('5. Items that depend on W05: W07, W10, W12, W15, W20', [(154, 155), (163, 164), (169, 170), (178, 179), (193, 194)]),
    ('6. Where coverage is shown to the user: W17 and W18', [(184, 185), (187, 188)]),
    ('7. Dependency graph and its notes', [(245, 267), (269, 269), (271, 271), (274, 274)]),
    ('8. Audit references that name W05', [(200, 201), (205, 205), (209, 209), (219, 219), (222, 222), (235, 235)]),
    ('9. Ownership register: scope, source rights and repository changes', [(280, 282), (285, 286)]),
    ('10. Blocker register: external terms and qualified inputs', [(291, 292), (295, 295), (297, 297)]),
    ('11. Section K: coverage and running-application conditions, population, the three ratios (θI, θF, θA)', [(318, 318), (322, 322), (325, 335)]),
    ('12. Section K: how thresholds are set, and why none is set now', [(345, 345), (347, 347), (349, 349)]),
]


def fail(code, message):
    sys.stderr.write(message + '\n')
    sys.exit(code)


def main():
    if len(sys.argv) != 2:
        fail(2, 'usage: extract_roadmap_lines.py <roadmap.md>')
    with open(sys.argv[1], 'rb') as handle:
        data = handle.read()
    blob = hashlib.sha1(b'blob %d\x00' % len(data) + data).hexdigest()
    digest = hashlib.sha256(data).hexdigest()
    if blob != GIT_BLOB or digest != SHA256:
        fail(3, 'the file is Git blob %s, SHA-256 %s; the recorded roadmap is blob %s, SHA-256 %s' % (blob, digest, GIT_BLOB, SHA256))
    lines = data.decode('utf-8').split('\n')

    out = []
    out.append('# Roadmap text that governs W05: verbatim extract')
    out.append('')
    out.append('Generated by `extract_roadmap_lines.py`. Do not edit by hand. Every fenced block below is the exact text of the named lines; nothing is paraphrased.')
    out.append('')
    out.append('| Item | Value |')
    out.append('|---|---|')
    out.append('| Repository | `ramkivs/iips-production-market-data` (IPD) |')
    out.append('| File | `%s` |' % ROADMAP_PATH)
    out.append('| `main` when read | `%s` |' % MAIN_COMMIT)
    out.append('| Last commit that changed the file | `%s` |' % LAST_CHANGED_BY)
    out.append('| Git blob | `%s` |' % GIT_BLOB)
    out.append('| SHA-256 | `%s` |' % SHA256)
    out.append('| Size | %d bytes, %d lines |' % (len(data), len(lines) - (1 if lines[-1] == '' else 0)))
    out.append('')
    out.append('Lines that are not listed are not reproduced. Lines 9 to 15 (authority records) and 337 to 343 (the monetary gate θM) are among them.')
    for title, ranges in SECTIONS:
        out.append('')
        out.append('## ' + title)
        for first, last in ranges:
            out.append('')
            out.append('Line %d' % first if first == last else 'Lines %d to %d' % (first, last))
            out.append('')
            out.append('````text')
            out.extend(lines[first - 1:last])
            out.append('````')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
