#!/usr/bin/env node
/**
 * IIPS — W-02 Windows DPAPI acceptance harness
 *
 * Runs ONLY on a Windows host, driven by `Invoke-W02DpapiAcceptance.ps1`.
 * It is not part of the shipped product and is never imported by `src/`.
 *
 * WHAT IT PROVES (real, on the operator's machine)
 *   - real `ProtectedData.Protect` / `Unprotect` at `DataProtectionScope.CurrentUser`;
 *   - both governed carriers written through the production atomic writer into the
 *     acceptance directory, with owner-only DACLs applied by the PRODUCTION applier
 *     (`dhan_dpapi_acl.ts` → real `Get-Acl` / `Set-Acl` child programs);
 *   - a repeated directory-DACL application is a no-op: an already-correct directory DACL is
 *     verified, never rewritten (the unconditional rewrite raised PrivilegeNotHeldException);
 *   - both carriers read back through the PRODUCTION backend
 *     (`WindowsDpapiHostVaultBackend`), compared to the generated throwaway values;
 *   - carrier separation, readiness gating, and the typed fail-closed negatives;
 *   - the values appear in no output, no carrier file, no argv and no error message.
 *
 * WHAT IT NEVER DOES
 *   - uses a Dhan credential (every value is generated by the caller and is throwaway);
 *   - prints a value, a ciphertext or raw child-process stderr;
 *   - passes data on argv, through a temporary file, or through a shell.
 *
 * PROTOCOL
 *   stdin  : {"clientIdValue":"…","accessTokenValue":"…","carrierRoot":"…"}
 *   stdout : one JSON object — {"ok":bool,"tests":[{id,description,step,status,exitCode,output}]}
 *   exit   : 0 all tests passed, 1 any test failed
 *
 * The generated values are supplied by the PowerShell wrapper over stdin precisely so that
 * they never appear on a command line, and so the wrapper can scan the evidence log for them.
 */

import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DIST = resolve(HERE, '..', 'dist', 'src', 'providers', 'dhan');

// ─────────────────────────────────────────────────────────────────────────────
// Static Windows program used only for enrolment (W-04 owns the real one).
// DACL reading and application are NOT here: they are production code
// (`read-acl` / `apply-acl` in dhan_dpapi_process.ts, driven by dhan_dpapi_acl.ts).
//
// The production tree owns `unprotect` and the ACL *check* (dhan_dpapi_process.ts).
// W-02 deliberately does not own `protect` or the ACL *apply* — that is W-04 — so the
// harness carries its own static copies of those two programs. They contain no data and
// are delivered with -EncodedCommand, exactly like the production scripts.
// ─────────────────────────────────────────────────────────────────────────────

const PROTECT_SCRIPT = [
  "$ErrorActionPreference = 'Stop'",
  'try {',
  '  Add-Type -AssemblyName System.Security',
  '  $raw = [Console]::In.ReadToEnd()',
  '  $req = $raw | ConvertFrom-Json',
  '  $bytes = [Convert]::FromBase64String([string]$req.plaintextB64)',
  '  $prot = [System.Security.Cryptography.ProtectedData]::Protect($bytes, $null, [System.Security.Cryptography.DataProtectionScope]::CurrentUser)',
  '  @{ ok = $true; ciphertextB64 = [Convert]::ToBase64String($prot) } | ConvertTo-Json -Compress',
  '} catch {',
  "  @{ ok = $false; kind = 'DPAPI_PROTECT_FAILED' } | ConvertTo-Json -Compress",
  '}',
].join('\n');

/** Runs a static PowerShell program; request JSON on stdin, result JSON on stdout only. */
function runPowerShell(scriptText, payload) {
  return new Promise((resolvePromise) => {
    let settled = false;
    const finish = (outcome) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolvePromise(outcome);
    };

    let child;
    try {
      child = spawn(
        'powershell.exe',
        [
          '-NoProfile',
          '-NonInteractive',
          '-ExecutionPolicy',
          'Bypass',
          '-EncodedCommand',
          Buffer.from(scriptText, 'utf16le').toString('base64'),
        ],
        { stdio: ['pipe', 'pipe', 'pipe'], windowsHide: true, shell: false }
      );
    } catch {
      resolvePromise({ kind: 'spawn-failed', stdout: '' });
      return;
    }

    const timer = setTimeout(() => {
      try {
        child.kill('SIGKILL');
      } catch {
        /* already gone */
      }
      finish({ kind: 'timeout', stdout: '' });
    }, 30_000);

    let stdout = '';
    let stderrBytes = 0;
    child.stdout?.setEncoding('utf8');
    child.stdout?.on('data', (chunk) => {
      stdout += chunk;
    });
    // Counted only. Never copied, never printed, never returned.
    child.stderr?.on('data', (chunk) => {
      stderrBytes += Buffer.byteLength(chunk);
    });
    child.on('error', () => finish({ kind: 'spawn-failed', stdout: '' }));
    child.on('close', (code) => {
      if (code !== 0) {
        finish({ kind: 'non-zero-exit', stdout: '' });
        return;
      }
      finish({ kind: 'ok', stdout, stderrBytes });
    });

    try {
      child.stdin.end(JSON.stringify(payload), 'utf8');
    } catch {
      finish({ kind: 'spawn-failed', stdout: '' });
    }
  });
}

/** Parses a JSON result from a child, tolerating a single-object answer. */
function parseChildJson(outcome) {
  if (outcome.kind !== 'ok') return null;
  try {
    const parsed = JSON.parse(outcome.stdout);
    return parsed && typeof parsed === 'object' ? parsed : null;
  } catch {
    return null;
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// Result collection
// ─────────────────────────────────────────────────────────────────────────────

const results = [];
let secretValues = [];
let secretsToGuard = [];

function record(id, description, step, status, output, exitCode = 0) {
  results.push({
    id,
    description,
    step,
    status,
    exitCode,
    output: sanitise(output, 220),
  });
}

function sanitise(text, limit) {
  let out = String(text === undefined || text === null ? '' : text).replace(/\s+/g, ' ').trim();
  for (const secret of secretsToGuard) {
    if (secret && secret.length > 0) {
      out = out.split(secret).join('[REDACTED]');
    }
  }
  if (out.length > limit) out = `${out.slice(0, limit)}…`;
  return out;
}

/** Structural guard: no value and no ciphertext may reach stdout, in any form. */
function guardOutput(payloadObject) {
  const serialised = JSON.stringify(payloadObject);
  const leaks = [];
  for (const secret of secretsToGuard) {
    if (secret && secret.length > 0 && serialised.includes(secret)) leaks.push('value');
  }
  return leaks;
}

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) chunks.push(chunk);
  return Buffer.concat(chunks).toString('utf8');
}

function reasonOf(error) {
  return error && typeof error === 'object' && typeof error.reason === 'string' ? error.reason : null;
}

function loadProductionModules() {
  if (!existsSync(join(DIST, 'dhan_dpapi_vault_backend.js'))) {
    return null;
  }
  return { distPath: DIST };
}

// ─────────────────────────────────────────────────────────────────────────────
// Main
// ─────────────────────────────────────────────────────────────────────────────

async function main() {
  let request;
  try {
    request = JSON.parse(await readStdin());
  } catch {
    record('W02-WIN-00', 'Acceptance harness input', 'read stdin JSON', 'FAIL', 'input was not valid JSON', 1);
    return;
  }

  const clientIdValue = String(request.clientIdValue || '');
  const accessTokenValue = String(request.accessTokenValue || '');
  const carrierRoot = String(request.carrierRoot || '');
  secretValues = [clientIdValue, accessTokenValue];
  secretsToGuard = [...secretValues];

  if (clientIdValue.length === 0 || accessTokenValue.length === 0 || carrierRoot.length === 0) {
    record('W02-WIN-00', 'Acceptance harness input', 'read stdin JSON', 'FAIL', 'a required input field was empty', 1);
    return;
  }

  if (process.platform !== 'win32') {
    record('W02-WIN-01', 'Windows platform', 'process.platform', 'FAIL', `platform is ${process.platform}`, 1);
    return;
  }

  if (loadProductionModules() === null) {
    record(
      'W02-WIN-01',
      'Built production modules',
      'dist/src/providers/dhan/dhan_dpapi_vault_backend.js',
      'FAIL',
      'the build is missing; run the TypeScript build first',
      1
    );
    return;
  }

  const carrier = await import('../dist/src/providers/dhan/dhan_dpapi_carrier.js');
  const processModule = await import('../dist/src/providers/dhan/dhan_dpapi_process.js');
  const aclModule = await import('../dist/src/providers/dhan/dhan_dpapi_acl.js');
  const backendModule = await import('../dist/src/providers/dhan/dhan_dpapi_vault_backend.js');
  const resolverModule = await import('../dist/src/providers/dhan/dhan_local_vault_resolver.js');
  const secretRef = await import('../dist/src/security/secret_ref.js');
  const configModule = await import('../dist/src/providers/dhan/dhan_config.js');

  const { writeDpapiCarrierAtomically, parseDpapiCarrierEnvelope, dpapiCarrierPathFor } = carrier;
  const { createPowerShellDpapiProcessRunner, dpapiPowerShellArgs } = processModule;
  const { WindowsDpapiHostVaultBackend } = backendModule;
  const { DhanVaultResolutionError } = resolverModule;
  const { DHAN_CLIENT_ID_KEY_PATH, DHAN_ACCESS_TOKEN_KEY_PATH } = secretRef;
  const { resolveDhanProviderConfig, DHAN_ENV_KEYS } = configModule;

  const now = new Date();
  const asOfUtc = now.toISOString();

  // Production references, built exactly as the daemon builds them.
  const config = resolveDhanProviderConfig(
    {
      [DHAN_ENV_KEYS.clientIdSecretPath]: DHAN_CLIENT_ID_KEY_PATH,
      [DHAN_ENV_KEYS.accessTokenSecretPath]: DHAN_ACCESS_TOKEN_KEY_PATH,
      [DHAN_ENV_KEYS.secretVaultProvider]: 'WINDOWS_DPAPI',
      [DHAN_ENV_KEYS.secretVersion]: 'v1',
    },
    now
  );
  if (config.ok !== true) {
    record('W02-WIN-01', 'Production credential references', 'resolveDhanProviderConfig', 'FAIL', 'configuration did not resolve', 1);
    return;
  }
  const clientRef = config.config.clientIdRef;
  const tokenRef = config.config.accessTokenRef;

  const productionRunner = createPowerShellDpapiProcessRunner();

  // The DACL policy and its application are PRODUCTION code: the harness composes
  // `createWindowsDpapiAclApplier` exactly as the provisioning utility will, so the run below
  // verifies the shipped implementation rather than a stand-in. The applier reads the descriptor,
  // verifies the exact owner-only policy and issues `Set-Acl` only when it actually differs —
  // the unconditional second rewrite is what raised PrivilegeNotHeldException on the host.
  const applyOwnerOnlyAcl = aclModule.createWindowsDpapiAclApplier({ runner: productionRunner });

  const protect = async (value) => {
    const outcome = await runPowerShell(PROTECT_SCRIPT, {
      plaintextB64: Buffer.from(value, 'utf8').toString('base64'),
    });
    const parsed = parseChildJson(outcome);
    if (!parsed || parsed.ok !== true || typeof parsed.ciphertextB64 !== 'string') return null;
    return parsed.ciphertextB64;
  };

  // ── W02-WIN-02: real DPAPI round trip ────────────────────────────────────
  const clientCiphertext = await protect(clientIdValue);
  const tokenCiphertext = await protect(accessTokenValue);
  if (!clientCiphertext || !tokenCiphertext) {
    record('W02-WIN-02', 'Real DPAPI Protect (CurrentUser)', 'ProtectedData.Protect', 'FAIL', 'protect did not return ciphertext', 1);
    return;
  }
  secretsToGuard = [...secretValues, clientCiphertext, tokenCiphertext];

  const roundTrip = await productionRunner({
    operation: 'unprotect',
    payload: { ciphertextB64: clientCiphertext },
  });
  let roundTripValue = null;
  if (roundTrip.kind === 'ok') {
    try {
      const parsed = JSON.parse(roundTrip.stdout);
      if (parsed.ok === true && typeof parsed.plaintextB64 === 'string') {
        roundTripValue = Buffer.from(parsed.plaintextB64, 'base64').toString('utf8');
      }
    } catch {
      roundTripValue = null;
    }
  }
  record(
    'W02-WIN-02',
    'Real DPAPI Protect/Unprotect round trip at DataProtectionScope.CurrentUser',
    'ProtectedData.Protect → production unprotect child process → compare',
    roundTripValue === clientIdValue ? 'PASS' : 'FAIL',
    roundTripValue === clientIdValue
      ? 'ciphertext produced and decrypted by the OS; recovered value equals the generated value'
      : 'the recovered value did not equal the generated value',
    roundTrip.kind === 'ok' ? 0 : 1
  );
  if (roundTripValue !== clientIdValue) return;

  // ── W02-WIN-03/04: carriers written through the production atomic writer ──
  const createdAtUtc = now.toISOString();
  const tokenExpiryUtc = new Date(now.getTime() + 24 * 60 * 60 * 1000).toISOString();

  const writeCarrier = async (role, envelope, testId, description) => {
    try {
      const written = await writeDpapiCarrierAtomically({
        carrierDirectory: carrierRoot,
        role,
        envelope,
        applyOwnerOnlyAcl,
        now,
      });
      const text = readFileSync(written.carrierPath, 'utf8');
      const parsed = parseDpapiCarrierEnvelope(text, { now });
      const plaintextAbsent = !text.includes(role === 'clientId' ? clientIdValue : accessTokenValue);
      const ok = parsed.ok === true && plaintextAbsent;
      record(
        testId,
        description,
        `writeDpapiCarrierAtomically(${role}) → parse → plaintext scan`,
        ok ? 'PASS' : 'FAIL',
        ok
          ? `carrier written, schema version accepted, no plaintext in the carrier file, directory DACL rewritten: ${written.directoryAclRewritten ? 'yes' : 'no'}`
          : 'carrier written but failed parse or contained plaintext',
        0
      );
      return ok ? written : null;
    } catch (error) {
      record(testId, description, `writeDpapiCarrierAtomically(${role})`, 'FAIL', `write failed (${error && error.name ? error.name : 'error'})`, 1);
      return false;
    }
  };

  const clientWritten = await writeCarrier(
    'clientId',
    {
      schemaVersion: carrier.DPAPI_CARRIER_SCHEMA_VERSION,
      secretId: clientRef.secretId,
      vaultProvider: 'WINDOWS_DPAPI',
      version: clientRef.version,
      createdAtUtc,
      rotatedAtUtc: createdAtUtc,
      ciphertext: clientCiphertext,
    },
    'W02-WIN-03',
    'Client id carrier written atomically at vault://dhan/client-id'
  );
  if (!clientWritten) return;

  const tokenWritten = await writeCarrier(
    'accessToken',
    {
      schemaVersion: carrier.DPAPI_CARRIER_SCHEMA_VERSION,
      secretId: tokenRef.secretId,
      vaultProvider: 'WINDOWS_DPAPI',
      version: tokenRef.version,
      createdAtUtc,
      rotatedAtUtc: createdAtUtc,
      expiresAtUtc: tokenExpiryUtc,
      ciphertext: tokenCiphertext,
    },
    'W02-WIN-04',
    'Access token carrier written atomically at vault://dhan/access-token'
  );
  if (!tokenWritten) return;

  // ── W02-WIN-05/06: read back through the production backend ───────────────
  const backend = new WindowsDpapiHostVaultBackend({
    carrierDirectory: carrierRoot,
    processRunner: productionRunner,
  });

  const readAndCompare = async (ref, expected, testId, description) => {
    try {
      const recordValue = await backend.readSecret(ref, asOfUtc);
      const ok = recordValue !== null && recordValue.secretValue === expected;
      record(
        testId,
        description,
        'WindowsDpapiHostVaultBackend.readSecret',
        ok ? 'PASS' : 'FAIL',
        ok ? 'decrypted value equals the generated value' : 'the backend did not return the generated value',
        0
      );
      return ok ? recordValue : null;
    } catch (error) {
      record(testId, description, 'WindowsDpapiHostVaultBackend.readSecret', 'FAIL', `rejected (${reasonOf(error) || 'unknown'})`, 1);
      return null;
    }
  };

  const clientRecord = await readAndCompare(
    clientRef,
    clientIdValue,
    'W02-WIN-05',
    'Client id carrier read back through the production backend'
  );
  if (clientRecord === null) return;

  const tokenRecord = await readAndCompare(
    tokenRef,
    accessTokenValue,
    'W02-WIN-06',
    'Access token carrier read back through the production backend'
  );
  if (tokenRecord === null) return;

  const tokenExpiryPreserved = tokenRecord.expiresAt === tokenExpiryUtc;
  record(
    'W02-WIN-06B',
    'Access token expiry metadata preserved through the backend',
    'compare record.expiresAt to the enrolled expiresAtUtc',
    tokenExpiryPreserved ? 'PASS' : 'FAIL',
    tokenExpiryPreserved ? 'expiry metadata matched' : 'expiry metadata did not match',
    0
  );

  // ── W02-WIN-07: the two carriers are genuinely separate ───────────────────
  const clientPath = dpapiCarrierPathFor(carrierRoot, 'clientId');
  const tokenPath = dpapiCarrierPathFor(carrierRoot, 'accessToken');
  let crossReadReason = null;
  try {
    await backend.readSecret({ ...clientRef, secretId: tokenRef.secretId }, asOfUtc);
  } catch (error) {
    crossReadReason = error instanceof DhanVaultResolutionError ? error.reason : 'NOT_A_VAULT_ERROR';
  }
  const separationOk =
    clientPath !== tokenPath &&
    clientCiphertext !== tokenCiphertext &&
    clientIdValue !== accessTokenValue &&
    clientRecord.secretValue !== tokenRecord.secretValue &&
    crossReadReason === 'SECRET_ID_MISMATCH';
  record(
    'W02-WIN-07',
    'Carrier separation: distinct files, distinct ciphertext, no cross-read',
    'compare carrier paths/ciphertext/values; read the client carrier with the token secret id',
    separationOk ? 'PASS' : 'FAIL',
    separationOk
      ? 'carriers are distinct and a cross-read is refused with SECRET_ID_MISMATCH'
      : `separation check failed (cross-read reason: ${crossReadReason || 'none'})`,
    0
  );

  // ── W02-WIN-08: DACL evidence and readiness gating ───────────────────────
  const unprobedVerdict = backend.describeReadiness();
  const probedVerdict = await backend.probeReadiness();
  const aclOutcome = await productionRunner({
    operation: 'describe-acl',
    payload: { paths: [carrierRoot, clientPath, tokenPath] },
  });
  let aclOk = false;
  if (aclOutcome.kind === 'ok') {
    try {
      const parsed = JSON.parse(aclOutcome.stdout);
      const items = Array.isArray(parsed.items) ? parsed.items : [parsed.items];
      aclOk =
        parsed.ok === true &&
        items.length === 3 &&
        items.every(
          (item) =>
            item &&
            item.exists === true &&
            item.protected === true &&
            item.onlyOwnerAndSystem === true &&
            item.ownerIsCurrentUser === true
        );
    } catch {
      aclOk = false;
    }
  }
  const readinessOk = unprobedVerdict.liveResolutionSupported === false && probedVerdict.liveResolutionSupported === true && aclOk;
  record(
    'W02-WIN-08',
    'Owner-only DACL on the directory and both carriers; readiness gated on a probe',
    'describeReadiness → probeReadiness → production describe-acl',
    readinessOk ? 'PASS' : 'FAIL',
    readinessOk
      ? 'unprobed verdict false, probed verdict true, directory and both carriers owner-only'
      : 'readiness or DACL evidence did not meet the gate',
    0
  );

  // ── W02-WIN-08B: repeated directory ACL application is a no-op ────────────
  // The host failure this run guards against: the second carrier write rewrote an
  // already-correct directory DACL and raised PrivilegeNotHeldException. Both the write
  // result and an explicit second application must report "no change, verified".
  let secondApply = null;
  let secondApplyError = null;
  try {
    secondApply = await applyOwnerOnlyAcl(carrierRoot, 'directory');
  } catch (error) {
    secondApplyError = error;
  }
  const idempotentOk =
    tokenWritten.directoryAclRewritten === false &&
    secondApply !== null &&
    secondApply.changed === false &&
    secondApply.verified === true;
  record(
    'W02-WIN-08B',
    'Repeated directory DACL application is a no-op (no unnecessary Set-Acl)',
    'writeDpapiCarrierAtomically(accessToken) then createWindowsDpapiAclApplier(directory) again',
    idempotentOk ? 'PASS' : 'FAIL',
    idempotentOk
      ? 'the second carrier write did not rewrite the directory DACL and a second application reported changed=false, verified=true'
      : `the access-token write or the second application still rewrote the DACL${secondApplyError ? ' (application failed)' : ''}`,
    0
  );

  // ── W02-WIN-09: typed fail-closed negatives ──────────────────────────────
  const negatives = [];
  const tamperDir = join(carrierRoot, 'negative-tamper');
  mkdirSync(tamperDir, { recursive: true });
  await applyOwnerOnlyAcl(tamperDir, 'directory');
  const tamperedCiphertext = `${clientCiphertext.slice(0, -4)}AAAA`;
  const tamperedPath = dpapiCarrierPathFor(tamperDir, 'clientId');
  writeFileSync(
    tamperedPath,
    JSON.stringify(
      {
        schemaVersion: carrier.DPAPI_CARRIER_SCHEMA_VERSION,
        secretId: clientRef.secretId,
        vaultProvider: 'WINDOWS_DPAPI',
        version: clientRef.version,
        createdAtUtc,
        rotatedAtUtc: createdAtUtc,
        ciphertext: tamperedCiphertext,
      },
      null,
      2
    ),
    'utf8'
  );
  await applyOwnerOnlyAcl(tamperedPath, 'file');
  const tamperBackend = new WindowsDpapiHostVaultBackend({
    carrierDirectory: tamperDir,
    processRunner: productionRunner,
  });
  try {
    await tamperBackend.readSecret(clientRef, asOfUtc);
    negatives.push('tampered:TAMPER_ACCEPTED');
  } catch (error) {
    negatives.push(`tampered:${reasonOf(error) || 'unknown'}`);
  }

  const missingDir = join(carrierRoot, 'negative-missing');
  mkdirSync(missingDir, { recursive: true });
  await applyOwnerOnlyAcl(missingDir, 'directory');
  const missingBackend = new WindowsDpapiHostVaultBackend({
    carrierDirectory: missingDir,
    processRunner: productionRunner,
  });
  try {
    await missingBackend.readSecret(clientRef, asOfUtc);
    negatives.push('missing:MISSING_ACCEPTED');
  } catch (error) {
    negatives.push(`missing:${reasonOf(error) || 'unknown'}`);
  }

  const negativesOk =
    negatives.includes('tampered:CARRIER_UNREADABLE') && negatives.includes('missing:CARRIER_MISSING');
  record(
    'W02-WIN-09',
    'Typed fail-closed negatives: tampered ciphertext and a missing carrier',
    'read a tampered carrier and a missing carrier through the production backend',
    negativesOk ? 'PASS' : 'FAIL',
    negativesOk ? 'tampered → CARRIER_UNREADABLE, missing → CARRIER_MISSING' : `unexpected outcomes (${negatives.join(', ')})`,
    0
  );

  // ── W02-WIN-10: non-exposure ─────────────────────────────────────────────
  const evidenceObject = { results };
  const outputLeaks = guardOutput(evidenceObject);

  let carrierPlaintextLeaks = 0;
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
        continue;
      }
      let text = '';
      try {
        text = readFileSync(full, 'utf8');
      } catch {
        text = '';
      }
      for (const secret of secretValues) {
        if (text.includes(secret)) carrierPlaintextLeaks += 1;
      }
    }
  };
  walk(carrierRoot);

  const argvLeaks = [...dpapiPowerShellArgs('unprotect'), ...dpapiPowerShellArgs('describe-acl')].filter(
    (argument) => secretsToGuard.some((secret) => argument.includes(secret))
  ).length;

  const nonExposureOk = outputLeaks.length === 0 && carrierPlaintextLeaks === 0 && argvLeaks === 0;
  record(
    'W02-WIN-10',
    'Secret non-exposure: values absent from output, carrier files, argv and errors',
    'serialise the result object, walk every acceptance file, inspect the production argv',
    nonExposureOk ? 'PASS' : 'FAIL',
    nonExposureOk
      ? 'no value in the result object, no plaintext on disk, no data on argv'
      : `leaks: output=${outputLeaks.length}, files=${carrierPlaintextLeaks}, argv=${argvLeaks}`,
    0
  );
}

// ─────────────────────────────────────────────────────────────────────────────
// Entry point — always emits exactly one JSON object, never a value
// ─────────────────────────────────────────────────────────────────────────────

let failure = null;
try {
  await main();
} catch (error) {
  failure = error && error.name ? error.name : 'error';
  results.push({
    id: 'W02-WIN-00',
    description: 'Acceptance harness execution',
    step: 'main()',
    status: 'FAIL',
    exitCode: 1,
    output: `unhandled harness failure (${failure}); the underlying message is not reproduced`,
  });
}

const guardLeak = guardOutput({ results });
if (guardLeak.length > 0) {
  results.push({
    id: 'W02-WIN-10B',
    description: 'Output guard',
    step: 'pre-emit scan',
    status: 'FAIL',
    exitCode: 1,
    output: 'a secret value would have been emitted; it has been redacted',
  });
}

const ok = results.length > 0 && results.every((r) => r.status === 'PASS');
process.stdout.write(`${JSON.stringify({ ok, tests: results })}\n`);
process.exit(ok ? 0 : 1);
